import { afterEach, expect, test, vi } from 'vitest'
import { ExpiringCache } from './cache'

afterEach(() => vi.useRealTimers())

test('evicts the least recently used value at capacity and disposes replaced/deleted values', () => {
  vi.useFakeTimers()
  const removed = vi.fn()
  const cache = new ExpiringCache<string, string>(2, 1000, removed)
  cache.set('a', 'A')
  cache.set('b', 'B')
  expect(cache.get('a')).toBe('A')
  cache.set('c', 'C')
  expect(cache.size).toBe(2)
  expect(cache.peek('b')).toBeUndefined()
  expect(removed).toHaveBeenCalledWith('b', 'B')
  cache.set('a', 'new A')
  expect(removed).toHaveBeenCalledWith('a', 'A')
  cache.delete('a')
  cache.clear()
  expect(cache.size).toBe(0)
  expect(vi.getTimerCount()).toBe(0)
})

test('expires idle entries without another read and reading does not prolong stale results', () => {
  vi.useFakeTimers()
  const removed = vi.fn()
  const cache = new ExpiringCache<string, object>(3, 1000, removed)
  cache.set('a', {})
  vi.advanceTimersByTime(500)
  cache.set('b', {})
  cache.get('a')
  vi.advanceTimersByTime(500)
  expect(cache.size).toBe(1)
  expect(removed.mock.calls.map(([key]) => key)).toEqual(['a'])
  vi.advanceTimersByTime(500)
  expect(cache.size).toBe(0)
  expect(vi.getTimerCount()).toBe(0)
})

test('a replacement survives the old deadline, using at most one timer', () => {
  vi.useFakeTimers()
  const cache = new ExpiringCache<string, number>(10, 1000)
  cache.set('a', 1)
  vi.advanceTimersByTime(500)
  cache.set('a', 2)
  vi.advanceTimersByTime(500)
  expect(cache.get('a')).toBe(2)
  vi.advanceTimersByTime(500)
  expect(cache.peek('a')).toBeUndefined()
  for (let i = 0; i < 100; i++) cache.set(String(i), i)
  expect(cache.size).toBe(10)
  expect(vi.getTimerCount()).toBe(1)
  cache.clear()
  vi.advanceTimersByTime(1000)
  expect(cache.size).toBe(0)
  expect(vi.getTimerCount()).toBe(0)
})

test('an expired value is rejected even if a background tab delayed the cleanup timer', () => {
  vi.useFakeTimers()
  const cache = new ExpiringCache<string, object>(2, 1000)
  cache.set('a', {})
  vi.setSystemTime(Date.now() + 1001)
  expect(cache.get('a')).toBeUndefined()
  expect(cache.size).toBe(0)
  expect(vi.getTimerCount()).toBe(0)
})
