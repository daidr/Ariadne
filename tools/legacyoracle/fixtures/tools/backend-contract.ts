/** Freeze the existing backend's externally visible surface before replacing it. */
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import ts from 'typescript'
import { PROJECTION_VERSION } from '../packages/core/src/ariadne'
import { EventStore } from '../packages/core/src/store'
import { defaultProjections } from '../packages/core/src/projections'
import { setupFiles } from '../packages/core/src/files'
import { setupSharedState } from '../packages/core/src/shared-state'

const root = join(import.meta.dir, '..')
const out = join(root, 'internal', 'compat', 'testdata')
const source = (path: string) => {
  const text = readFileSync(join(root, path), 'utf8')
  return ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true)
}
const routes: { method: string; path: string; source: string }[] = []
const app = source('packages/server/src/app.ts')
function visit(node: ts.Node) {
  if (ts.isCallExpression(node) && node.expression.getText(app) === 'add') {
    const [method, path] = node.arguments
    if (!method || !path || !ts.isStringLiteral(method) || !ts.isStringLiteral(path)) {
      throw new Error(`Non-literal route at ${node.getStart(app)} needs explicit accounting`)
    }
    routes.push({
      method: method.text,
      path: path.text,
      source: app.fileName,
    })
  }
  ts.forEachChild(node, visit)
}
visit(app)
// These routes are authenticated outside the ordinary HTTP router.
routes.push(
  { method: 'GET', path: '/api/health', source: 'packages/server/src/app.ts' },
  { method: 'GET', path: '/api/files/:fileId', source: 'packages/server/src/app.ts' },
  { method: 'HEAD', path: '/api/files/:fileId', source: 'packages/server/src/app.ts' },
  { method: 'WS', path: '/api/artifacts/:artifactId/live', source: 'packages/server/src/app.ts' },
)
const eventSource = source('packages/core/src/events.ts')
const map = eventSource.statements.find(
  (node): node is ts.InterfaceDeclaration =>
    ts.isInterfaceDeclaration(node) && node.name.text === 'EventMap',
)!
const events = map.members.map((node) => {
  if (!ts.isPropertySignature(node) || !node.name) throw new Error('Unknown event declaration')
  return ts.isStringLiteral(node.name) ? node.name.text : node.name.getText(eventSource)
})
const baseline = new EventStore({ path: ':memory:', projections: defaultProjections })
try {
  setupFiles(baseline.db)
  setupSharedState(baseline.db)
  const schema = baseline.db
    .query<{ type: string; name: string; sql: string }, []>(
      `SELECT type, name, sql FROM sqlite_master
       WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
       AND name NOT GLOB 'search_text_*'
       ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name`,
    )
    .all()
  const manifest = {
    format: 1,
    go: '1.27.4',
    projectionVersion: PROJECTION_VERSION,
    routes: routes.toSorted((a, b) =>
      `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`),
    ),
    events: events.toSorted(),
    schema,
  }
  const artifacts = {
    'backend-contract.json': `${JSON.stringify(manifest, null, 2)}\n`,
    'schema.sql': `${schema.map((row) => `${row.sql};`).join('\n\n')}\n`,
  }
  const outputs = Object.entries(artifacts).map(([name, text]) => [join(out, name), text] as const)
  outputs.push([join(root, 'internal/schema/schema.sql'), artifacts['schema.sql']])
  // Freeze the exact property accepted by the existing emoji validator. This is
  // generated test-time data; the Go runtime does not run JavaScript.
  const emoji = /\p{Extended_Pictographic}|\p{Regional_Indicator}/u
  const ranges: [number, number][] = []
  let first = -1
  for (let point = 0; point <= 0x110000; point++) {
    const matches = point < 0x110000 && emoji.test(String.fromCodePoint(point))
    if (matches && first < 0) first = point
    if (!matches && first >= 0) {
      ranges.push([first, point - 1])
      first = -1
    }
  }
  outputs.push([
    join(root, 'internal/textutil/emoji_ranges.go'),
    '// Code generated by tools/backend-contract.ts; DO NOT EDIT.\n\npackage textutil\n\nvar emojiRanges = [][2]rune{\n' +
      ranges.map(([from, to]) => `\t{0x${from.toString(16)}, 0x${to.toString(16)}},`).join('\n') +
      '\n}\n',
  ])
  for (const [path, text] of outputs) {
    if (process.argv.includes('--check')) {
      if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== text) {
        throw new Error(`${path} has drifted: run bun tools/backend-contract.ts`)
      }
    } else {
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, text)
    }
  }
  console.info(
    `${routes.length} routes, ${events.length} event types, ${schema.length} schema objects; ` +
      `sha256 ${createHash('sha256').update(artifacts['backend-contract.json']).digest('hex')}`,
  )
} finally {
  baseline.close()
}
